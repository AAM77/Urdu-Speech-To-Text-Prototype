# ── Route presence tests ──────────────────────────────────────────────────────


_EXPECTED_PATHS = [
    # health
    ("/health", "get"),
    # auth
    ("/auth/login", "post"),
    ("/auth/logout", "post"),
    # tokens
    ("/tokens", "post"),
    ("/tokens", "get"),
    ("/tokens/{token_id}", "delete"),
    # single-part upload
    ("/uploads/init", "post"),
    ("/uploads/{upload_id}", "get"),
    ("/uploads/{upload_id}/complete", "post"),
    # multipart upload
    ("/uploads/multipart/init", "post"),
    ("/uploads/multipart/{upload_id}/parts/{part_number}", "get"),
    ("/uploads/multipart/{upload_id}/complete", "post"),
    ("/uploads/multipart/{upload_id}", "delete"),
    # direct upload
    ("/uploads/direct", "post"),
    # runs
    ("/runs", "post"),
    ("/runs", "get"),
    ("/runs/{run_id}", "get"),
    ("/runs/{run_id}/events", "get"),
    ("/runs/{run_id}/cancel", "post"),
    # artifacts (nested under runs and as top-level)
    ("/runs/{run_id}/artifacts", "get"),
    ("/artifacts/{artifact_id}", "get"),
    ("/artifacts/{artifact_id}/download", "get"),
]


@pytest.mark.parametrize("path,method", _EXPECTED_PATHS)
def test_expected_route_is_documented(schema, path, method):
    """Every public route must appear in the OpenAPI schema."""
    assert path in schema["paths"], f"Missing path: {path}"
    assert method in schema["paths"][path], f"Missing method {method.upper()} for {path}"


# ── No internal identifier leakage ────────────────────────────────────────────


def test_user_id_not_in_any_schema_property(schema):
    """user_id must never appear as a schema property — it is internal."""
    all_props = _all_property_names(schema.get("components", {}).get("schemas", {}))
    assert "user_id" not in all_props, (
        "user_id appeared as a property name in a schema component. "
        "It must never be returned to or accepted from callers."
    )


def test_job_id_not_in_any_response_schema(schema):
    """job_id must not appear in any schema — it is an internal queue concept."""
    all_props = _all_property_names(schema.get("components", {}).get("schemas", {}))
    assert "job_id" not in all_props


def test_object_key_not_in_any_schema(schema):
    """Raw object-store keys must never be part of the public API surface."""
    all_props = _all_property_names(schema.get("components", {}).get("schemas", {}))
    assert "object_key" not in all_props
    assert "key" not in all_props


def test_no_provider_fields_in_any_schema(schema):
    """Provider configuration must not be controllable by callers."""
    all_props = _all_property_names(schema.get("components", {}).get("schemas", {}))
    for forbidden in ("provider", "model_id", "prompt", "api_key"):
        assert forbidden not in all_props, (
            f"Forbidden field {forbidden!r} appeared in schema. "
            "Provider/model/prompt fields must not be caller-controlled."
        )


# ── Token raw-value policy ────────────────────────────────────────────────────


def test_token_list_schema_does_not_include_raw_token(schema):
    """TokenListResponse/TokenSummary must not expose the raw token value."""
    token_list = schema.get("components", {}).get("schemas", {}).get("TokenListResponse", {})
    props = _all_property_names(token_list)
    assert "token" not in props, (
        "TokenListResponse exposes the raw 'token' field. "
        "The raw value must only appear in the creation response."
    )


def test_token_summary_does_not_include_raw_token(schema):
    summary = schema.get("components", {}).get("schemas", {}).get("TokenSummary", {})
    props = _all_property_names(summary)
    assert "token" not in props


# ── Request schema extra-field policy ─────────────────────────────────────────


def test_upload_init_request_does_not_accept_user_id(schema):
    """InitUploadRequest must not accept user_id from callers."""
    req_schema = schema.get("components", {}).get("schemas", {}).get("InitUploadRequest", {})
    assert req_schema, "InitUploadRequest schema not found in components"
    props = set((req_schema.get("properties") or {}).keys())
    assert "user_id" not in props
    assert "object_key" not in props


def test_run_request_does_not_accept_provider_fields(schema):
    """CreateRunRequest must not accept provider or model configuration."""
    req_schema = schema.get("components", {}).get("schemas", {}).get("CreateRunRequest", {})
    assert req_schema, "CreateRunRequest schema not found"
    props = set((req_schema.get("properties") or {}).keys())
    assert "provider" not in props
    assert "model_id" not in props
    assert "prompt" not in props


# ── Snapshot generation (not a test, called by a test) ───────────────────────


def test_openapi_snapshot_is_saved(schema):
    """Write the current schema to docs/openapi.json for human review and diffing.

    This test always passes; the generated file is the deliverable.
    """
    workspace = Path(__file__).parent.parent.parent
    docs_dir = workspace / "docs"
    docs_dir.mkdir(exist_ok=True)
    output = docs_dir / "openapi.json"
    output.write_text(json.dumps(schema, indent=2, ensure_ascii=False))
    assert output.exists()
