"""OpenAPI schema validation tests — Step 4.3.5.

Tests validate key properties of the generated schema without requiring a
brittle full-content snapshot.  The assertions focus on:

  1. The schema is reachable and structurally valid.
  2. All expected public routes are documented.
  3. No internal identifiers (user_id, job_id, raw object keys, provider
     details) appear in any request or response schema.
  4. The one-time raw token value is not exposed in list or summary schemas.
  5. No prohibited provider/model/prompt fields appear anywhere.

A machine-readable snapshot is generated by the implementation step and
saved to ``docs/openapi.json`` for offline review and diffing.
"""

from __future__ import annotations

import json
from pathlib import Path

import pytest
from fastapi.testclient import TestClient

from urdu_pipeline.api.app import create_app
from urdu_pipeline.api.dependencies import AppState
from urdu_pipeline.infrastructure.in_memory import (
    InMemoryCacheStore,
    InMemoryMetadataStore,
    InMemoryObjectStore,
    InMemorySecretProvider,
)


# ── Fixture ───────────────────────────────────────────────────────────────────


@pytest.fixture(scope="module")
def schema() -> dict:
    """Fetch the OpenAPI schema from the app once for all tests in this module."""
    state = AppState(
        metadata_store=InMemoryMetadataStore(),
        object_store=InMemoryObjectStore(),
        cache_store=InMemoryCacheStore(),
        secret_provider=InMemorySecretProvider(),
    )
    client = TestClient(create_app(state=state))
    resp = client.get("/openapi.json")
    assert resp.status_code == 200, "OpenAPI schema endpoint must return 200"
    return resp.json()


# ── Helper ────────────────────────────────────────────────────────────────────


def _all_property_names(obj: object) -> set[str]:
    """Recursively extract every property name from a JSON Schema object."""
    names: set[str] = set()
    if isinstance(obj, dict):
        if "properties" in obj and isinstance(obj["properties"], dict):
            names.update(obj["properties"].keys())
        for v in obj.values():
            names.update(_all_property_names(v))
    elif isinstance(obj, list):
        for item in obj:
            names.update(_all_property_names(item))
    return names


# ── Structural tests ──────────────────────────────────────────────────────────


